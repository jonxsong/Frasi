import asyncio
from collections import defaultdict
from datetime import UTC, datetime

from celery import Task
from frasi_api.config import get_settings
from frasi_api.database import SessionLocal
from frasi_api.models import (
    JobStatus,
    Measure,
    NoteEvent,
    Recording,
    ScoreRevision,
    TempoEvent,
    TranscriptionJob,
    TranscriptionProject,
    Voice,
)
from frasi_api.storage import get_storage
from frasi_ml import TranscriptionPipeline, TranscriptionResult
from sqlalchemy import func, select
from sqlalchemy.ext.asyncio import AsyncSession
from sqlalchemy.orm import selectinload

from .celery_app import celery_app

settings = get_settings()


async def update_job(job_id: str, *, stage: str, progress: float) -> None:
    async with SessionLocal() as session:
        job = await session.get(TranscriptionJob, job_id)
        if job is None:
            raise ValueError(f"Unknown transcription job: {job_id}")
        job.stage = stage
        job.progress = progress
        await session.commit()


async def persist_result(
    session: AsyncSession,
    project: TranscriptionProject,
    job: TranscriptionJob,
    result: TranscriptionResult,
) -> ScoreRevision:
    latest = await session.scalar(
        select(func.max(ScoreRevision.revision)).where(ScoreRevision.project_id == project.id)
    )
    revision = ScoreRevision(
        project_id=project.id,
        revision=(latest or 0) + 1,
        source="transcription",
        musicxml=result.musicxml,
        edit_summary="Generated by the Frasi DSP transcription pipeline",
    )
    session.add(revision)
    await session.flush()

    events_by_measure = defaultdict(list)
    for event in result.notes:
        events_by_measure[event.measure].append(event)
    for number, events in sorted(events_by_measure.items()):
        measure = Measure(
            revision_id=revision.id,
            number=number,
            beats=result.time_signature[0],
            beat_type=result.time_signature[1],
        )
        session.add(measure)
        await session.flush()
        voice = Voice(measure_id=measure.id, number=1)
        session.add(voice)
        await session.flush()
        for event in events:
            session.add(
                NoteEvent(
                    voice_id=voice.id,
                    concert_midi=event.concert_midi,
                    spelling=event.spelling,
                    is_rest=False,
                    performance_onset_seconds=event.performance.onset_seconds,
                    performance_offset_seconds=event.performance.offset_seconds,
                    pitch_confidence=event.performance.pitch_confidence,
                    onset_confidence=event.performance.onset_confidence,
                    beat_numerator=event.beat.numerator,
                    beat_denominator=event.beat.denominator,
                    duration_numerator=event.duration.numerator,
                    duration_denominator=event.duration.denominator,
                    tuplet_actual=event.tuplet[0] if event.tuplet else None,
                    tuplet_normal=event.tuplet[1] if event.tuplet else None,
                    tie_start=event.tie_start,
                    tie_stop=event.tie_stop,
                )
            )

    for point in result.tempo_map:
        session.add(
            TempoEvent(
                revision_id=revision.id,
                at_seconds=point.at_seconds,
                measure_number=point.beat_index // result.time_signature[0] + 1,
                beat_numerator=point.beat_index % result.time_signature[0],
                beat_denominator=1,
                bpm=point.bpm,
            )
        )

    project.current_revision_id = revision.id
    project.instrument_id = result.instrument
    project.time_signature_beats = result.time_signature[0]
    project.time_signature_beat_type = result.time_signature[1]
    job.status = JobStatus.SUCCEEDED
    job.stage = "complete"
    job.progress = 1
    job.completed_at = datetime.now(UTC)
    job.intermediate_manifest = result.stage_metrics
    await session.commit()
    return revision


async def process_job(job_id: str) -> str:
    async with SessionLocal() as session:
        job = await session.scalar(
            select(TranscriptionJob)
            .options(
                selectinload(TranscriptionJob.project)
                .selectinload(TranscriptionProject.recording)
                .selectinload(Recording.assets)
            )
            .where(TranscriptionJob.id == job_id)
        )
        if job is None:
            raise ValueError(f"Unknown transcription job: {job_id}")
        if job.status == JobStatus.SUCCEEDED:
            return job.project.current_revision_id or ""
        project = job.project
        asset = next((item for item in project.recording.assets if item.kind == "original"), None)
        if asset is None:
            raise ValueError("Recording has no original audio asset")
        job.status = JobStatus.PROCESSING
        job.stage = "loading_audio"
        job.progress = 0.05
        job.attempts += 1
        job.started_at = datetime.now(UTC)
        await session.commit()

        storage = get_storage(settings)
        async with storage.materialize(asset.storage_key) as path:
            await update_job(job_id, stage="transcribing_pitch_and_rhythm", progress=0.2)
            result = await asyncio.to_thread(
                TranscriptionPipeline().transcribe_file,
                path,
                start=project.segment_start_seconds,
                duration=project.segment_end_seconds - project.segment_start_seconds,
                instrument=project.instrument_id,
            )
        await update_job(job_id, stage="building_symbolic_score", progress=0.85)
        return (await persist_result(session, project, job, result)).id


async def record_failure(job_id: str, message: str, *, retrying: bool) -> None:
    async with SessionLocal() as session:
        job = await session.get(TranscriptionJob, job_id)
        if job is None:
            return
        job.status = JobStatus.QUEUED if retrying else JobStatus.FAILED
        job.stage = "retrying" if retrying else "failed"
        job.error_code = "processing_failed"
        job.error_message = message[:1000]
        if not retrying:
            job.completed_at = datetime.now(UTC)
        await session.commit()


@celery_app.task(
    bind=True,
    name="frasi.transcribe",
    acks_late=True,
    soft_time_limit=60 * 30,
    time_limit=60 * 35,
    max_retries=2,
)
def transcribe_task(self: Task, job_id: str) -> str:
    try:
        return asyncio.run(process_job(job_id))
    except Exception as exc:
        retrying = self.request.retries < self.max_retries
        asyncio.run(record_failure(job_id, str(exc), retrying=retrying))
        if retrying:
            raise self.retry(exc=exc, countdown=5 * (2**self.request.retries)) from exc
        raise
